"""Autonomous Multi-Format Executive Report Generator (Day 5 Deliverable).

Author: Vidhita (Document Engineer)
Pair: Pair D (Documents + Messaging)
Module: creator.report_maker

Generates comprehensive, multi-format executive intelligence reports across:
- Publication-quality PDF reports with executive cover pages and bento metrics.
- Formatted Word DOCX documents with structured tables and typography.
- 16:9 widescreen PowerPoint presentation slide decks with chart visualisations.

Combines automated chart generation, Bento grid KPI cards, data tables,
and narrative sections into a synchronized executive document package.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
import re
from typing import Any, Dict, List, Optional, Sequence, Union

from creator.chart_maker import generate_chart
from creator.docx_maker import make_docx
from creator.pdf_maker import make_pdf
from creator.pptx_maker import make_pptx
from creator.themes import THEMES, get_theme

logger = logging.getLogger(__name__)


def generate_executive_report(
    title: str,
    summary: str,
    sections: Optional[List[Dict[str, Any]]] = None,
    key_metrics: Optional[List[Dict[str, str]]] = None,
    chart_configs: Optional[List[Dict[str, Any]]] = None,
    theme: str = "clean_light",
    formats: Optional[List[str]] = None,
    out_dir: str = "workspace",
    auto_open: bool = False,
) -> Dict[str, str]:
    """Generate a coordinated multi-format executive report package.

    Args:
        title: Title of the executive report.
        summary: Executive summary narrative text.
        sections: Optional additional content sections with headings, text, bullets, or tables.
        key_metrics: Optional list of KPI metric dicts: [{'label': 'Latency', 'value': '<250ms'}, ...].
        chart_configs: Optional list of chart configs to generate and embed:
            [{'type': 'bar', 'data': {'labels': [...], 'values': [...]}, 'title': 'Growth'}, ...]
        theme: Theme name ('clean_light', 'dark_pro', 'colourful').
        formats: Target formats list (e.g. ['pdf', 'docx', 'pptx']). Defaults to all three.
        out_dir: Directory where generated files are stored (default: 'workspace').
        auto_open: If True, opens the primary generated file on Windows.

    Returns:
        Dict[str, str]: Mapping of format name ('pdf', 'docx', 'pptx') to resolved filesystem path.

    Raises:
        ValueError: If title is empty.
        RuntimeError: If document generation fails.
    """
    if not title or not isinstance(title, str) or not title.strip():
        raise ValueError("Report title must be a non-empty string.")

    target_formats = [f.lower().strip() for f in (formats or ["pdf", "docx", "pptx"])]
    target_dir = Path(out_dir).resolve()
    target_dir.mkdir(parents=True, exist_ok=True)

    # 1. Prepare Executive Summary Section
    assembled_sections: List[Dict[str, Any]] = []

    exec_summary_section: Dict[str, Any] = {
        "heading": "1. Executive Summary",
        "text": summary.strip() if summary else "Autonomous executive intelligence report generated by Project JARVIS.",
    }
    if key_metrics and isinstance(key_metrics, list):
        exec_summary_section["metrics"] = key_metrics
        exec_summary_section["bento_cards"] = key_metrics

    assembled_sections.append(exec_summary_section)

    # 2. Add Custom Sections
    if sections and isinstance(sections, list):
        for idx, sec in enumerate(sections):
            if isinstance(sec, dict):
                assembled_sections.append(dict(sec))

    # 3. Process & Generate Chart Visualisations
    generated_charts: List[str] = []
    if chart_configs and isinstance(chart_configs, list):
        for c_idx, cfg in enumerate(chart_configs):
            if isinstance(cfg, dict):
                c_type = cfg.get("type", "bar")
                c_data = cfg.get("data", {})
                c_title = cfg.get("title", f"Visualisation {c_idx + 1}")
                try:
                    c_path = generate_chart(
                        chart_type=c_type,
                        data=c_data,
                        title=c_title,
                        theme=theme,
                        out_dir=str(target_dir),
                    )
                    generated_charts.append(c_path)

                    # Append a dedicated visual analytics section for this chart
                    assembled_sections.append({
                        "heading": f"Data Visualisation: {c_title}",
                        "text": f"Graphical breakdown ({c_type.title()} Chart) corresponding to key performance indicators.",
                        "chart_path": c_path,
                    })
                except Exception as chart_err:
                    logger.warning("Failed to render chart %s: %s", c_title, chart_err)

    # 4. Generate Output Files Across Requested Formats
    output_files: Dict[str, str] = {}
    primary_file_to_open: Optional[str] = None

    try:
        if "pdf" in target_formats:
            pdf_path = make_pdf(
                title=title,
                sections=assembled_sections,
                theme=theme,
                out_dir=str(target_dir),
                subtitle="Autonomous Executive Intelligence Package",
                auto_open=False,  # defer auto_open to coordinated launcher
            )
            output_files["pdf"] = pdf_path
            if not primary_file_to_open:
                primary_file_to_open = pdf_path

        if "docx" in target_formats:
            docx_path = make_docx(
                title=title,
                sections=assembled_sections,
                theme=theme,
                out_dir=str(target_dir),
                subtitle="Autonomous Executive Intelligence Package",
                auto_open=False,
            )
            output_files["docx"] = docx_path
            if not primary_file_to_open:
                primary_file_to_open = docx_path

        if "pptx" in target_formats:
            pptx_path = make_pptx(
                title=title,
                sections=assembled_sections,
                theme=theme,
                out_dir=str(target_dir),
                subtitle="Autonomous Executive Intelligence Package",
                auto_open=False,
            )
            output_files["pptx"] = pptx_path
            if not primary_file_to_open:
                primary_file_to_open = pptx_path

    except Exception as exc:
        logger.error("Report generation failed: %s", exc, exc_info=True)
        raise RuntimeError(f"Report generation encountered an error: {exc}") from exc

    # 5. Handle Coordinated Auto-Open
    if auto_open and primary_file_to_open:
        try:
            if hasattr(os, "startfile"):
                os.startfile(primary_file_to_open)
                logger.info("Auto-opened report file: %s", primary_file_to_open)
        except Exception as open_err:
            logger.warning("Auto-open encountered non-fatal error: %s", open_err)

    logger.info("Executive report successfully produced %d formats: %s", len(output_files), list(output_files.keys()))
    return output_files
