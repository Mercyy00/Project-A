"""
Google Antigravity Agent and IDE Bridge Tool for JARVIS.

Ported from Mark LVI's antigravity_engine.py.
Allows JARVIS to formulate prompt-engineered directives, save them to the Antigravity Prompts directory,
copy them to clipboard, and focus the Google Antigravity IDE.
"""

from __future__ import annotations

import os
import sys
import time
import subprocess
from pathlib import Path
from datetime import datetime
from typing import Any, Dict, Optional

from tools.base import BaseTool, ToolResult


class AntigravityPromptTool(BaseTool):
    """Bridges JARVIS directives into the running Google Antigravity IDE."""
    name: str = "antigravity_prompt"
    description: str = (
        "Formulates an optimized AI coding prompt for Google Antigravity, copies it to the clipboard, "
        "and focuses the Antigravity IDE window."
    )

    def get_schema(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "parameters": {
                "type": "object",
                "properties": {
                    "task": {
                        "type": "string",
                        "description": "High-level goal or problem statement to hand off to Antigravity."
                    },
                    "context": {
                        "type": "string",
                        "description": "Optional background files, errors, or constraints."
                    }
                },
                "required": ["task"]
            }
        }

    def run(self, task: str, context: Optional[str] = None, **kwargs) -> ToolResult:
        try:
            ts = datetime.now().strftime("%Y%m%d_%H%M%S")
            sanitized_title = "_".join(task.split()[:5]).lower()
            sanitized_title = "".join(c for c in sanitized_title if c.isalnum() or c == "_")
            filename = f"{sanitized_title}_{ts}.md"

            prompts_dir = Path.home() / "Desktop" / "Antigravity_Prompts"
            prompts_dir.mkdir(parents=True, exist_ok=True)
            prompt_file = prompts_dir / filename

            prompt_content = f"""# ANTIGRAVITY DIRECTIVE: {task}
Generated by JARVIS MARK LVI on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

## Objective
{task}

## Context & Invariants
{context or 'Maintain existing architecture and verify changes with automated tests.'}

## Execution Rules
1. Ground before mutating.
2. Verify all outputs with deterministic tests.
3. Keep code clean, type-hinted, and robust.
"""
            prompt_file.write_text(prompt_content, encoding="utf-8")

            # Copy to clipboard
            try:
                import pyperclip
                pyperclip.copy(prompt_content)
            except Exception:
                pass

            # Focus Antigravity window if on Windows
            focused = False
            if sys.platform == "win32":
                try:
                    import win32gui, win32con
                    def enum_cb(hwnd, _):
                        nonlocal focused
                        if win32gui.IsWindowVisible(hwnd):
                            title = win32gui.GetWindowText(hwnd).lower()
                            if "antigravity" in title or "gemini" in title:
                                win32gui.ShowWindow(hwnd, win32con.SW_RESTORE)
                                win32gui.SetForegroundWindow(hwnd)
                                focused = True
                    win32gui.EnumWindows(enum_cb, None)
                except Exception:
                    pass

            return ToolResult(
                success=True,
                data={
                    "prompt_file": str(prompt_file.resolve()),
                    "antigravity_focused": focused
                },
                message=f"Antigravity directive formulated and copied to clipboard. File saved at {prompt_file.name}."
            )
        except Exception as exc:
            return ToolResult(
                success=False,
                message=f"Failed to formulate Antigravity directive: {str(exc)}"
            )
